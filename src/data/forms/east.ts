/** attested form */
const a = (lang: string, form: string, translit?: string, note?: string, ipa?: string): WordForm => ({
  lang,
  form,
  ...(translit ? { translit } : {}),
  ...(ipa ? { ipa } : {}),
  attested: true,
  ...(note ? { note } : {}),
});
/** reconstructed form (form must start with '*') */
